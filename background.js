import {
  migrateStoredSettings,
  resolveGlobalRoute,
  resolveTabRoute
} from "./src/core.js";

const ICON_PATHS = Object.freeze({
  proxy: { 16: "icons/status/proxy16.png", 32: "icons/status/proxy32.png" },
  direct: { 16: "icons/status/direct16.png", 32: "icons/status/direct32.png" },
  unknown: { 16: "icons/status/unknown16.png", 32: "icons/status/unknown32.png" }
});

// The titles describe the browser-level route only. They never claim to know
// which program is listening on the other end, or what it does with the request.
const ICON_TITLES = Object.freeze({
  proxy: "Alaxee Proxy · 此网页交给代理服务器",
  direct: "Alaxee Proxy · 此网页浏览器直连",
  unknown: "Alaxee Proxy · 当前网页状态未知，或代理设置由其他程序控制"
});

// The toolbar icons are static PNGs generated by scripts/render-icons.py.
// They used to be drawn at runtime into an OffscreenCanvas as well, duplicating
// the same artwork that also existed as an inline SVG in the popup and as these
// PNGs. Only the PNGs were shipped by the manifest, so the canvas path could not
// be the source of truth, and it cost eight draws on every cold start.
function chromeCall(target, method, ...args) {
  return new Promise((resolve, reject) => {
    try {
      target[method](...args, (result) => {
        const error = chrome.runtime.lastError;
        if (error) reject(new Error(error.message));
        else resolve(result);
      });
    } catch (error) {
      reject(error);
    }
  });
}

async function readContext() {
  const [stored, proxyState] = await Promise.all([
    chromeCall(chrome.storage.local, "get", "settings"),
    chromeCall(chrome.proxy.settings, "get", { incognito: false })
  ]);
  // Migration is applied on read but not written back here: the service worker
  // must not rewrite storage while the popup may be mid-edit. The popup owns the
  // write-back (popup-controller.js).
  const { settings } = migrateStoredSettings(stored?.settings);
  return { settings, proxyState };
}

async function setActionState(route, tabId) {
  const safeRoute = ICON_PATHS[route] ? route : "unknown";
  const target = tabId == null ? {} : { tabId };
  await chromeCall(chrome.action, "setIcon", { path: ICON_PATHS[safeRoute], ...target });
  await chromeCall(chrome.action, "setTitle", { title: ICON_TITLES[safeRoute], ...target });
}

async function refreshTab(tabId, context) {
  if (!Number.isInteger(tabId)) return;
  const runtime = context ?? await readContext();
  const tab = await chromeCall(chrome.tabs, "get", tabId).catch(() => null);
  const route = resolveTabRoute(tab?.url ?? "", runtime.proxyState, runtime.settings);
  await setActionState(route, tabId);
}

async function hasTabsPermission() {
  return chromeCall(chrome.permissions, "contains", { permissions: ["tabs"] });
}

async function refreshAllTabs() {
  const runtime = await readContext();
  const hasPermission = await hasTabsPermission();
  const tabs = await chromeCall(chrome.tabs, "query", {});

  if (!hasPermission) {
    // Never present the global mode as though it were the active page's route.
    // Unknown is the only truthful per-page state until URL access is granted.
    await setActionState("unknown");
    await Promise.all((tabs ?? [])
      .filter((tab) => Number.isInteger(tab.id))
      .map((tab) => setActionState("unknown", tab.id)));
    return;
  }

  const globalRoute = resolveGlobalRoute(runtime.proxyState, runtime.settings);
  await setActionState(globalRoute);
  await Promise.all((tabs ?? [])
    .filter((tab) => Number.isInteger(tab.id))
    .map((tab) => {
      const route = resolveTabRoute(tab.url ?? "", runtime.proxyState, runtime.settings);
      return setActionState(route, tab.id);
    }));
}

function refreshAllSafely() {
  void refreshAllTabs().catch((error) => {
    // Keep the extension silent in the background; the popup reports user-facing failures.
    console.warn("Alaxee Proxy status refresh failed:", error?.message ?? error);
  });
}

// A single user action fans out into several events: proxy.settings.onChange,
// plus two storage writes because the popup persists and then applies. Refreshing
// on each one multiplied the work - each refresh reads state and re-derives the
// route for every open tab. Coalesce them into one refresh per burst.
let pendingRefresh = null;

function scheduleRefresh(delayMs = 0) {
  if (pendingRefresh !== null) return;
  pendingRefresh = setTimeout(() => {
    pendingRefresh = null;
    refreshAllSafely();
  }, delayMs);
}

// Cancel a queued refresh and run it now, so a burst never leaves the icons stale.
function refreshNow() {
  if (pendingRefresh !== null) {
    clearTimeout(pendingRefresh);
    pendingRefresh = null;
  }
  refreshAllSafely();
}

chrome.runtime.onMessage.addListener((message, sender, sendResponse) => {
  if (sender.id !== chrome.runtime.id || message?.type !== "SYNC_ALL_TABS") return;

  // An explicit sync supersedes any coalesced refresh that is still queued.
  if (pendingRefresh !== null) {
    clearTimeout(pendingRefresh);
    pendingRefresh = null;
  }

  const reply = (payload) => {
    // The popup may be closing (pagehide) when it asks for this sync, in which
    // case the response port is already gone and replying throws.
    try {
      sendResponse(payload);
    } catch {
      // Nothing to report to; the icons were still updated.
    }
  };

  refreshAllTabs()
    .then(() => reply({ ok: true }))
    .catch((error) => reply({ ok: false, error: error?.message ?? "sync_failed" }));
  return true;
});

chrome.runtime.onInstalled.addListener(refreshNow);
chrome.runtime.onStartup.addListener(refreshNow);

// Proxy and storage changes arrive in bursts, so they are coalesced.
chrome.proxy.settings.onChange.addListener(() => scheduleRefresh(60));
chrome.storage.onChanged.addListener((changes, areaName) => {
  if (areaName === "local" && changes.settings) scheduleRefresh(60);
});

chrome.permissions.onAdded.addListener(refreshNow);
chrome.permissions.onRemoved.addListener(refreshNow);

chrome.tabs.onActivated.addListener(({ tabId }) => {
  void hasTabsPermission()
    .then((granted) => granted && refreshTab(tabId))
    .catch(() => {});
});

chrome.tabs.onUpdated.addListener((tabId, changeInfo) => {
  if (!changeInfo.url && changeInfo.status !== "complete") return;
  void hasTabsPermission()
    .then((granted) => granted && refreshTab(tabId))
    .catch(() => {});
});

refreshAllSafely();
